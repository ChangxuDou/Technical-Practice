import math
print(round(2.9))  # round rounds to the nearest whole number
print(abs(-2.9))  # abs returns the absolute value of a number
print(math.ceil(2.9))  # ceil rounds up to the nearest whole number
print(math.floor(2.9))  # floor rounds down to the nearest whole number

# we can also use the math module to find the square root of a number
print(math.sqrt(16))  # square root of 16 is 4

