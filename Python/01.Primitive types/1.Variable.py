course = "Python Programming"
print(len(course))  # use len() function to get the length of the string
# use square brackets to access individual characters in a string
print(course[0])
# use negative indexing to access the last character in a string
print(course[-1])
print(course[0:3])  # use slicing to get a substring from the string
print(course[0:])  # use slicing to get the entire string
# use slicing to get the first three characters of the string
print(course[:3])
print(course[:])  # use slicing to get the entire string
